#!/usr/bin/env bash
# Bakes the git commit count into DriverVersion.h so the running driver
# reports its build in "BRIDGE_ACK v1 <count>". Mirrors
# scripts/bake-driver-version.ps1 so Linux CI stamps the identical header.
# An explicit first argument wins (release workflow); otherwise git
# rev-list --count HEAD, or "dev" when git is unavailable.
# Never edit DriverVersion.h by hand.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
version="dev"

if [ $# -ge 1 ] && [ -n "$1" ]; then
    version="$1"
else
    if count="$(git -C "$root" rev-list --count HEAD 2>/dev/null)" && [ -n "$count" ]; then
        version="$count"
    fi
fi

version_header="$root/driver_cardboardplusplus/include/DriverVersion.h"
cat > "$version_header" <<EOF
#pragma once
// Driver build version: the git commit count at compile time.
//
// Regenerated by scripts/bake-driver-version.sh (Linux CI) or
// scripts/bake-driver-version.ps1 (Windows CI) from \`git rev-list --count HEAD\`
// before every build, so the running driver always reports the commit it
// was built from. The fallback below ("dev") is only used when the header
// was never generated (e.g. a source export without the script); never
// edit this file by hand.
#define DRIVER_BUILD_VERSION "$version"
EOF

echo "Driver version: $version"
